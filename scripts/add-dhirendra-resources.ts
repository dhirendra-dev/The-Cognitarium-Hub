async function addMaterials() {
  const db = await getDb();
  if (!db) {
    console.error("Failed to connect to database");
    process.exit(1);
  }

  try {
    console.log(`Adding ${additionalMaterials.length} new study materials...`);
    let added = 0;
    for (const material of additionalMaterials) {
      try {
        await db.insert(studyMaterialsTable).values(material);
        added++;
      } catch (err: any) {
        // Ignore duplicate entries
        if (!err.message.includes("Duplicate")) {
          console.error(`Error adding ${material.title}:`, err.message);
        }
      }
    }
    console.log(`✓ Successfully added ${added} new study materials`);
  } catch (error) {
    console.error("Error adding materials:", error);
    process.exit(1);
  }
}

addMaterials();
